import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import ExcelJS from 'exceljs';
import { saveAs } from 'file-saver';

// --- CSV Exporter ---
export const exportToCSV = (data: any[], headers: string[], keys: string[], filename: string) => {
  // Format rows
  const csvRows = [];
  
  // Headers row
  csvRows.push(headers.map(h => `"${h.replace(/"/g, '""')}"`).join(','));
  
  // Data rows
  for (const row of data) {
    const values = keys.map(key => {
      const val = row[key] !== undefined && row[key] !== null ? String(row[key]) : '';
      return `"${val.replace(/"/g, '""')}"`;
    });
    csvRows.push(values.join(','));
  }

  const csvContent = '\uFEFF' + csvRows.join('\n'); // Add UTF-8 BOM
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  saveAs(blob, `${filename}.csv`);
};

// --- Excel Exporter (Styled via exceljs) ---
interface ExcelSheetConfig {
  name: string;
  headers: string[];
  keys: string[];
  data: any[];
}

export const exportToExcel = async (sheets: ExcelSheetConfig[], filename: string) => {
  const workbook = new ExcelJS.Workbook();

  sheets.forEach((sheetConfig) => {
    const worksheet = workbook.addWorksheet(sheetConfig.name);
    
    // Add Headers
    const headerRow = worksheet.addRow(sheetConfig.headers);
    headerRow.height = 25;
    
    // Style Header Row
    headerRow.eachCell((cell) => {
      cell.fill = {
        type: 'pattern',
        pattern: 'solid',
        fgColor: { argb: 'FF161D30' } // Navy card color
      };
      cell.font = {
        name: 'Arial',
        color: { argb: 'FFFFFFFF' },
        bold: true,
        size: 10
      };
      cell.alignment = { vertical: 'middle', horizontal: 'left' };
      cell.border = {
        bottom: { style: 'medium', color: { argb: 'FF0284C7' } } // blue line
      };
    });

    // Add Data
    sheetConfig.data.forEach((row) => {
      const dataRowValues = sheetConfig.keys.map(key => {
        const val = row[key];
        return val !== undefined && val !== null ? val : '';
      });
      worksheet.addRow(dataRowValues);
    });

    // Freeze panes: Freeze header row
    worksheet.views = [{ state: 'frozen', ySplit: 1 }];

    // Auto-fit Columns
    worksheet.columns.forEach((column) => {
      let maxLen = 0;
      column.eachCell!((cell) => {
        const len = cell.value ? String(cell.value).length : 0;
        if (len > maxLen) maxLen = len;
      });
      column.width = Math.max(maxLen + 3, 12); // Minimum 12 width
    });
  });

  const buffer = await workbook.xlsx.writeBuffer();
  const blob = new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  saveAs(blob, `${filename}.xlsx`);
};

// --- PDF Exporter (jsPDF + AutoTable) ---
interface PDFReportConfig {
  title: string;
  subtitle?: string;
  headers: string[];
  keys: string[];
  data: any[];
  metadata: {
    user: string;
    company: string;
  };
}

export const exportToPDF = (config: PDFReportConfig, filename: string) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const timestamp = new Date().toLocaleString();

  // Draw Cover/Title Block
  doc.setFillColor(11, 15, 25); // #0b0f19
  doc.rect(0, 0, 210, 45, 'F');

  // Title Text
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(config.title.toUpperCase(), 15, 20);

  // Subtitle Text
  doc.setTextColor(156, 163, 175); // gray-400
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(config.subtitle || 'GRC compliance report', 15, 28);

  // Metadata block
  doc.setTextColor(100, 116, 139); // Slate-500
  doc.setFontSize(8);
  doc.text(`Organization: ${config.metadata.company}`, 15, 36);
  doc.text(`Generated By: ${config.metadata.user} | ${timestamp}`, 15, 40);

  // Confidential notice
  doc.setTextColor(239, 68, 68); // Red
  doc.setFont('helvetica', 'bold');
  doc.text('CONFIDENTIAL - ENTERPRISE GRC DATA', 140, 12);

  // Format Rows for AutoTable
  const bodyRows = config.data.map(item => {
    return config.keys.map(key => {
      const val = item[key];
      return val !== undefined && val !== null ? String(val) : '';
    });
  });

  // Render Table
  autoTable(doc, {
    startY: 55,
    head: [config.headers],
    body: bodyRows,
    theme: 'grid',
    headStyles: {
      fillColor: [22, 29, 48], // Navy card color
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
      lineColor: [35, 45, 69],
      lineWidth: 0.1
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.1
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252]
    },
    margin: { top: 55, bottom: 20, left: 15, right: 15 },
    didDrawPage: (data: any) => {
      // Running Page Footers
      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(148, 163, 184); // Slate-400
      
      const str = 'Page ' + doc.getNumberOfPages();
      doc.text(str, data.settings.margin.left, doc.internal.pageSize.height - 10);
      doc.text('Enterprise Risk Assessment Platform', 140, doc.internal.pageSize.height - 10);
    }
  });

  doc.save(`${filename}.pdf`);
};
